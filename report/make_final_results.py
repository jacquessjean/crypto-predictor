"""Writes docs/final-model-results.md from out/results/final_*.csv: python report/make_final_results.py"""
import json
import sys

import pandas as pd

sys.path.insert(0, "src")
from final_model import load_splits, random_baseline  # noqa: E402

R = "out/results/"
pct = lambda v: f"{100 * v:+.3f}%"


def table(df):
    head = "| " + " | ".join(df.columns) + " |\n| " + " | ".join("---" for _ in df.columns) + " |\n"
    return head + "".join("| " + " | ".join(str(v) for v in row) + " |\n" for row in df.itertuples(index=False))


base = pd.read_csv(R + "final_baseline.csv")
weigh = pd.read_csv(R + "final_weighting.csv")
cal = pd.read_csv(R + "final_calibration.csv")
dec = pd.read_csv(R + "final_decision.csv")
curve = pd.read_csv(R + "final_curve_val_b.csv")
exits = pd.read_csv(R + "final_exit.csv")
test = pd.read_csv(R + "final_test.csv").iloc[0]
decision = json.load(open("out/model/v1/decision.json"))
versions = json.load(open("out/model/v1/versions.json"))
val_b_fwd = load_splits()["val_b"]["fwd_ret"]
rand = {side: random_baseline(val_b_fwd, side) for side in ["buy", "sell"]}
got = {side: dec.query(f"side == '{side}' and split == 'val_b'").iloc[0] for side in ["buy", "sell"]}
verdict = lambda side: "better" if got[side].mean_net > rand[side] else "worse"

b = base.groupby("criterion").agg(log_loss=("log_loss", "mean"), brier=("brier", "mean"),
                                  buy10=("buy_mean_net@10%", "mean"), buy10_std=("buy_mean_net@10%", "std")).reset_index()
w = weigh.groupby("variant").agg(log_loss=("log_loss", "mean"), buy10=("buy_mean_net@10%", "mean"),
                                 buy10_std=("buy_mean_net@10%", "std"), sell10=("sell_mean_net@10%", "mean")).reset_index()
w = w.sort_values("buy10", ascending=False)

md = f"""# Final model results

Generated by `report/make_final_results.py` from `out/results/final_*.csv`. Model: 3-class Random Forest (up / flat /
down beyond the 0.2% fee over the next hour), 100 trees, depth 8, as designed in Phase IV. Tuning on val-A
(Oct 2024 - Feb 2025), confirmation on val-B (Mar - Jun 2025), one evaluation on the test period (Jul 2025 - Oct 2026).

**Shipped:** criterion `{decision['criterion']}`, variant `{decision['variant']}`, `{decision['calibration']}` calibration,
Buy margin {pct(decision['buy_margin'])} (expected net return), Sell {'on, margin ' + pct(decision['sell_margin']) if decision.get('sell_enabled', True) else 'switched off (section 4)'}, exit rule:
{'sell at the first Sell signal' if decision['early_exit'] else 'hold the full hour'}.

## 1. Criterion (val-A, mean over 3 seeds)

{table(b.assign(log_loss=b.log_loss.round(5), brier=b.brier.round(5), buy10=b.buy10.map(pct), buy10_std=b.buy10_std.map(pct)).rename(columns={'buy10': 'Buy net @10% of bars', 'buy10_std': 'std'}))}
The log-loss criterion of the design is kept: Gini does not beat it by more than the seed noise.

## 2. Weighting and feature selection (val-A, mean over 3 seeds)

{table(w.assign(log_loss=w.log_loss.round(5), buy10=w.buy10.map(pct), buy10_std=w.buy10_std.map(pct), sell10=w.sell10.map(pct)).rename(columns={'buy10': 'Buy net @10%', 'buy10_std': 'std', 'sell10': 'Sell net @10%'}))}
Rule fixed before running: a variant must beat no weighting by more than its own seed std. Weighting by the size of
the move and dropping the five features with no Phase III importance improves the Buy result most. Size weighting
distorts the raw probabilities (higher log loss), which calibration corrects.

## 3. Calibration (fitted on val-A)

{table(cal[['calibration', 'val_a_log_loss', 'val_b_log_loss', 'val_b_brier']].round(5))}

## 4. Decision margins (tuned on val-A, confirmed on val-B)

{table(dec.assign(margin=dec.margin.map(pct), share=dec.share.map(lambda v: f'{100 * v:.2f}%'), mean_net=dec.mean_net.map(pct), hit_rate=dec.hit_rate.round(3)))}
Val-B at fixed signal rates (expected-net-return ranking):

{table(curve.assign(margin=curve.margin.map(pct), mean_net=curve.mean_net.map(pct), hit_rate=curve.hit_rate.round(3))[['side', 'target_share', 'n', 'mean_net', 'hit_rate']])}
**No setting beats the fee on val-B.** The most confident 1% of Buy signals earned {pct(dec.query("side == 'buy' and split == 'val_a'").mean_net.iloc[0])} net on val-A but
{pct(dec.query("side == 'buy' and split == 'val_b'").mean_net.iloc[0])} on val-B. Sell signals almost never fire and are not reliable.

**Against acting at random (val-B, as the design requires):** buying at every bar averages {pct(rand['buy'])} net and selling
at every bar {pct(rand['sell'])}. Buy signals ({pct(got['buy'].mean_net)}, n={int(got['buy'].n)}) are {verdict('buy')} than buying at
random. Sell signals ({pct(got['sell'].mean_net)}, n={int(got['sell'].n)}) are {verdict('sell')} than selling at random{' -- **flagged: the design requires Sell not to be clearly worse than random**' if verdict('sell') == 'worse' else ''}.
Because of this, **Sell is switched off in the shipped model** (`sell_enabled: false` in decision.json): the app says
Wait instead. This was decided after seeing val-B and is disclosed as such; it does not change any Buy or test result.

## 5. Exit rule (val-B, one position per coin)

{table(exits.assign(mean_net=exits.mean_net.map(pct), hit_rate=exits.hit_rate.round(3)))}
Sell signals are too rare to change any exit, so the shipped rule holds the position for the full hour.

## 6. Test period (evaluated once)

Phase III evaluated binary models on this period; the 3-class model and its decision rule were evaluated on it once,
after every choice above was fixed. (The cell ran a second time only because the next cell failed; the result was
identical byte for byte.)

| Metric | Value |
| --- | --- |
| Rows | {int(test['rows']):,} |
| Log loss (class prior) | {test['log_loss']:.5f} ({test['prior_log_loss']:.5f}) |
| Buy signals | {int(test['buy_n'])} ({100 * test['buy_share']:.2f}% of bars) |
| Buy mean net return, hit rate | {pct(test['buy_mean_net'])}, {test['buy_hit_rate']:.3f} |
| Sell signals | {int(test['sell_n'])} |
| Simulated trades (one per coin at a time) | {int(test['trade_trades'])}, mean net {pct(test['trade_mean_net'])}, hit rate {test['trade_hit_rate']:.3f} |

The test period is positive after fees, but val-B was not: the evidence for a profitable edge is mixed and the number of
signals is small, so the application should present Buy as a weak, rare signal and Wait as the normal answer.

## 7. Artifact

`out/model/v1/`: model.pkl (calibrated pipeline taking the 36 scaled features), scaler.json, schema.json (version
{json.load(open('out/model/v1/schema.json'))['schema_version']}), decision.json, versions.json, check.npz. Library versions: {', '.join(f'{k} {v}' for k, v in versions.items())}.
Served by `service/model_service.py` (POST /v1/predict, GET /health) in the model container, with the artifact mounted
read-only.
"""
open("docs/final-model-results.md", "w").write(md)
print("written docs/final-model-results.md")
