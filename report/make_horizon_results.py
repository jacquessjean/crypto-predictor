"""Writes docs/horizon-results.md from out/results/horizon_*.csv: python report/make_horizon_results.py"""
import json

import pandas as pd

R = "out/results/"
pct = lambda v: f"{100 * v:+.3f}%"

summary = pd.read_csv(R + "horizon_summary.csv")
cand = pd.read_csv(R + "horizon_candidates.csv")
nov = pd.read_csv(R + "horizon_november.csv").iloc[0]
v1 = pd.read_csv(R + "final_exit.csv").query("early_exit == False").iloc[0]
decision = json.load(open("out/model/v2/decision.json"))

rows = ["| Horizon | Model | Val-B trades | Net per trade (mean ± std over seeds) | Hit rate | Random buying | Trustworthy |",
        "| --- | --- | --- | --- | --- | --- | --- |"]
for r in summary.itertuples():
    rows.append(f"| {r.horizon} | {r.model.replace('_', ' ')} | {r.trades:.0f} | {pct(r.mean_net)} ± {100 * r.std:.3f}% | "
                f"{r.hit:.1%} | {pct(r.random)} | {'yes' if r.trustworthy else 'no'} |")
seeds = cand[(cand.H == 4) & (cand.model == "random_forest")]

md = f"""# Trustworthy Buy signals: results

Generated by `report/make_horizon_results.py` from `out/results/horizon_*.csv`. Design:
`docs/superpowers/specs/2026-11-25-trustworthy-buy-design.md`; experiments: `src/horizons.ipynb`.

**Shipped: model v2**, a 1-hour Random Forest (the v1 pipeline) whose Buy margin is tuned on non-overlapping trades
(at least 100 on val-A): Buy only when the expected net return exceeds {pct(decision['buy_margin'])}. Sell stays off.

## Candidates on val-B (criterion fixed before any result was seen)

Trustworthy = at least 100 non-overlapping trades, mean net return per trade above zero, and better than random
buying, all averaged over three seeds. Val-B is not untouched data: earlier v1 choices (the calibration method, the
exit rule and switching Sell off) looked at it, and this round exists because of v1's val-B result. November is the
only data no decision has seen.

{chr(10).join(rows)}

The longer horizons did not help. They give fewer independent trades (below the 100 required) and their results vary
widely between seeds, and gradient boosting was worse than the Random Forest at every horizon (its number of
iterations sat at the edge of the grid, so it may be under-tuned). The gain comes from
the Buy rule instead: v1 tuned its margin per bar and fired on many overlapping, marginal signals
({int(v1['trades'])} trades on val-B, {pct(v1['mean_net'])} per trade); tuning it on real trades with a minimum of 100
keeps only the confident ones (val-B seeds: {', '.join(pct(v) for v in seeds.val_b_mean_net)} per trade).

## November 2026 (never seen before; checked once, and a rerun reloads the saved result)

| Metric | Value |
| --- | --- |
| Bars with a complete label | {int(nov['bars']):,} |
| Buy trades | {int(nov['trades'])} |
| Mean net return per trade | {pct(nov['mean_net'])} |
| 95% bootstrap interval | {pct(nov['ci_low'])} to {pct(nov['ci_high'])} |
| Hit rate | {nov['hit_rate']:.1%} |
| Buying at random | {pct(nov['random_mean_net'])} per trade ({int(nov['random_trades'])} trades) |
| Verdict (rule fixed in advance) | **{nov['verdict']}** |

The pass rule required at least 30 trades, a positive mean and a better result than random buying; all three hold.
The interval still includes zero because 38 trades is few, and it is probably too narrow: trades on different coins
at the same time move together, while the bootstrap treats them as independent. The hit rate is {nov['hit_rate']:.0%}, so
the positive mean comes from winning trades that were larger than the losing ones, not from being right more often.
The evidence is consistent (positive on val-B and on November, better than random both times) but not conclusive;
November is the only clean check.

## For the application

The horizon is unchanged (60 minutes), so the application needs no change. The model service now reports
`horizon_minutes` in /health and /v1/predict, and docker-compose serves `out/model/v2` (v1 is kept for rollback).
Expect fewer Buy signals than with v1: the margin is about ten times stricter.
"""
open("docs/horizon-results.md", "w").write(md)
print("written docs/horizon-results.md")
